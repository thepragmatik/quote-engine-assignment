import { z } from 'zod'
import type { components } from './generated'

/**
 * Direct TypeScript type representation of {@code QuoteRequest} generated
 * from {@code .github/specs/openapi.yaml}.
 */
export type OpenApiQuoteRequest = components['schemas']['QuoteRequest']

/**
 * Zod validation schema for client-side loan quote requests.
 *
 * @remarks
 * ATTENTION(security): This schema strictly mirrors the server-side Jakarta Bean Validation
 * annotations on {@code QuoteRequest} and the OpenAPI specification in {@code .github/specs/openapi.yaml}.
 *
 * Compile-time type assertions below guarantee that this runtime Zod schema evolves in tandem
 * with the OpenAPI specification generated by {@code npm run codegen}.
 */
export const quoteSchema = z.object({
  /**
   * Principal loan amount requested in currency units.
   * Bound: [$1,000.00, $10,000,000.00].
   */
  loanAmount: z
    .number({ message: 'Loan amount must be between $1,000 and $10,000,000.' })
    .min(1000, 'Loan amount must be between $1,000 and $10,000,000.')
    .max(10000000, 'Loan amount must be between $1,000 and $10,000,000.'),

  /**
   * Loan tenure duration in months.
   * Bound: [6, 360] integer months.
   */
  loanTermInMonths: z
    .number({ message: 'Loan term must be between 6 and 360 months.' })
    .int('Loan term must be between 6 and 360 months.')
    .min(6, 'Loan term must be between 6 and 360 months.')
    .max(360, 'Loan term must be between 6 and 360 months.'),

  /**
   * Operational risk assessment tier.
   * Permitted values: 'LOW' | 'MEDIUM' | 'HIGH'.
   */
  riskBand: z.enum(['LOW', 'MEDIUM', 'HIGH'], {
    message: 'Please select a valid risk band.',
  }),
})

/**
 * Inferred TypeScript payload type.
 */
export type QuotePayload = z.infer<typeof quoteSchema>

/**
 * Compile-time contract assertion:
 * Asserts that the Zod-inferred {@link QuotePayload} satisfies {@link OpenApiQuoteRequest}.
 * If the OpenAPI contract changes in `.github/specs/openapi.yaml`, running `npm run codegen`
 * updates `generated.ts`, causing immediate TypeScript compilation failure if the UI schema drifts.
 */
type AssertContractSynchronized = QuotePayload extends OpenApiQuoteRequest
  ? OpenApiQuoteRequest extends QuotePayload
    ? true
    : false
  : false

const _contractVerification: AssertContractSynchronized = true
void _contractVerification
