package com.bendigo.quote.resilience;

import java.math.BigDecimal;

/**
 * Port interface in the Hexagonal / Ports-and-Adapters architecture decoupling the quote domain
 * from the external partner vendor HTTP communication details.
 *
 * <p>The resilience-decorated HTTP client adapter is the production implementation. Test suites can
 * substitute a mock or stub bean without needing full HTTP transport simulation.
 */
public interface VendorQuotePort {

  /** Canonical API endpoint path for the partner quote verification service. */
  String VERIFY_PATH = "/api/v1/vendor/quotes";

  /**
   * Verifies partner eligibility and obtains a verification code for the given quote parameters.
   *
   * @param loanAmount requested principal amount
   * @param termMonths duration in months
   * @param riskBand customer operational risk tier
   * @return {@link VendorVerification} containing partner verification code and validation status
   * @throws VendorServiceUnavailableException on unrecoverable partner rejection (e.g. 400/401)
   * @throws RetryableVendorException on transient upstream failure after retries are exhausted
   * @throws CircuitOpenException when downstream circuit breaker is open
   */
  VendorVerification verify(BigDecimal loanAmount, int termMonths, String riskBand);

  /**
   * Verification payload returned by the external vendor partner.
   *
   * @param verificationCode unique tracking code generated by the partner service
   * @param verified boolean attesting whether the partner verified the loan parameters
   */
  record VendorVerification(String verificationCode, boolean verified) {}
}
